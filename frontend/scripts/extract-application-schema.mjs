/**
 * Mirrors the application form map into the backend seed.
 *
 *   frontend/src/features/applications/applicationSchema.ts
 *     -> backend/src/ExpertHub.Infrastructure/Persistence/
 *        ApplicationSchemaSeed.<version>.cs
 *
 * `applicationSchema.ts` is the single source of truth for the form (its own
 * header says so). The API serves the same object from `FORM_SCHEMA` /
 * `FORM_SECTION` / `FORM_FIELD` / `ATTACHMENT_RULE`, and `FORM_FIELD.definition`
 * carries the complete wire field object verbatim — so the two must be the same
 * bytes, not two hand-maintained copies. Earlier versions were extracted by an
 * ad-hoc script that was never checked in; this is that script, kept.
 *
 * It EVALUATES the real module with esbuild rather than parsing it, so a schema
 * the frontend cannot load is a schema this cannot emit.
 *
 * Usage, from `frontend/`:
 *     node scripts/extract-application-schema.mjs
 *
 * It writes ONE file per version and never edits an existing one — a published
 * version is history (`BR-0103`).
 */

import { build } from 'esbuild';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { existsSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const FRONTEND = path.resolve(import.meta.dirname, '..');
const REPO = path.resolve(FRONTEND, '..');
const ENTRY = path.join(FRONTEND, 'src/features/applications/applicationSchema.ts');
const OUT_DIR = path.join(REPO, 'backend/src/ExpertHub.Infrastructure/Persistence');

/**
 * The seed's own GUID scheme, continued: `<kind>000000-0000-0000-000V-<row>`,
 * where V is the version's ordinal in the chain and `row` is its 1-based
 * position. Readable in a database client, and stable.
 *
 * Ordinals 1–3 are the three versions that live in `ApplicationSeedData.cs`
 * (2026-08-30, 09-14, 09-16). Every version generated by this script takes the
 * next one, ordered by its own date — the version strings are `dm-gap-NN.
 * YYYY-MM-DD`, so sorting them lexicographically IS sorting them
 * chronologically. Deriving it from the set rather than hardcoding it means
 * re-running the script for any version reproduces that version's ids exactly,
 * which is what makes the refusal check below meaningful.
 */
const HANDWRITTEN_VERSIONS = 3;

function versionOrdinal(version, outDir) {
  const generated = readdirSync(outDir)
    .map((name) => /^ApplicationSchemaSeed\.(.+)\.cs$/.exec(name)?.[1])
    .filter(Boolean);
  const slug = version.replace(/[^a-zA-Z0-9]/g, '');
  const all = [...new Set([...generated, slug])].sort();
  return HANDWRITTEN_VERSIONS + all.indexOf(slug) + 1;
}

const guid = (kind, index, ordinal) =>
  `${kind}000000-0000-0000-${String(ordinal).padStart(4, '0')}-${String(index).padStart(12, '0')}`;

const csharp = (value) => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/**
 * The field object exactly as the wire carries it — key order preserved, and
 * `order` kept verbatim even when it is fractional. The schema uses fractions
 * (9.1, 9.2 …) to slot a new field between two existing ones without
 * renumbering the rest; `FORM_FIELD.order_index` is an int, so the COLUMN gets
 * the field's rank in this array while the served definition keeps the
 * fraction. Both express the same ordering, and the definition is what the
 * form renders from.
 */
const definitionJson = (field) => JSON.stringify(field);

async function loadSchema() {
  const dir = await mkdtemp(path.join(tmpdir(), 'eh-schema-'));
  const outfile = path.join(dir, 'schema.mjs');
  await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile,
    logLevel: 'silent',
  });
  const module = await import(pathToFileURL(outfile).href);
  await rm(dir, { recursive: true, force: true });
  return module.APPLICATION_FORM_SCHEMA;
}

function emit(schema) {
  const { version } = schema;
  const slug = version.replace(/[^a-zA-Z0-9]/g, '');
  const ordinal = versionOrdinal(version, OUT_DIR);

  const nullable = (value) => (value == null ? '(string?)null' : csharp(value));

  const sections = schema.sections.map(
    (section, index) => `        new
        {
            SectionId = new Guid(${csharp(guid('f5', index + 1, ordinal))}),
            SchemaVersion = Version,
            SectionCode = ${csharp(section.id)},
            TitleAr = ${csharp(section.titleAr)},
            TitleEn = ${csharp(section.titleEn)},
            OrderIndex = ${section.order},
            Repeatable = ${nullable(section.repeatable && JSON.stringify(section.repeatable))},
        },`
  );

  const fields = schema.fields.map(
    (field, index) => `        new
        {
            FieldId = new Guid(${csharp(guid('ff', index + 1, ordinal))}),
            SchemaVersion = Version,
            FieldCode = ${csharp(field.id)},
            SectionCode = ${csharp(field.sectionId)},
            LabelAr = ${csharp(field.labelAr)},
            LabelEn = ${csharp(field.labelEn)},
            InputType = ${csharp(field.type)},
            OrderIndex = ${index + 1},
            Definition = ${csharp(definitionJson(field))},
        },`
  );

  const attachments = schema.attachments.map(
    (rule, index) => `        new
        {
            RuleId = new Guid(${csharp(guid('fa', index + 1, ordinal))}),
            SchemaVersion = Version,
            RuleCode = ${csharp(rule.id)},
            LabelAr = ${csharp(rule.labelAr)},
            LabelEn = ${csharp(rule.labelEn)},
            AcceptedFormats = ${csharp(JSON.stringify(rule.acceptedFormats))},
            MaxSizeMb = ${rule.maxSizeMb},
            MaxCount = ${rule.maxCount},
            RequiredFor = ${csharp(JSON.stringify(rule.requiredFor))},
            PerEntryOf = ${nullable(rule.perEntryOf)},
        },`
  );

  return `using ExpertHub.Core.Domain;

namespace ExpertHub.Infrastructure.Persistence;

/// <summary>
/// The application form map, version <c>${version}</c>.
/// </summary>
/// <remarks>
/// ⚠️ GENERATED — do not edit by hand. Produced by
/// <c>frontend/scripts/extract-application-schema.mjs</c>, which EVALUATES
/// <c>applicationSchema.ts</c> (the form's single source of truth) rather than
/// retyping it, so the object the browser renders and the rows the API serves
/// are the same bytes.
///
/// A published version is history (<c>BR-0103</c>): this file is never edited
/// once its migration ships. A change to the form writes a NEW version beside
/// it, and every draft and application keeps the version it was answered
/// against.
/// </remarks>
internal static class ApplicationSchema${slug}
{
    internal const string Version = FormSchemaVersions.Current;

    internal static readonly object Schema = new
    {
        SchemaVersion = Version,
        Status = FormSchemaStatuses.Published,
        SelectableServices = ${csharp(JSON.stringify(schema.selectableServices))},
        PublishedAt = (DateTime?)new DateTime(${version.slice(-10).split('-').map(Number).join(', ')}, 0, 0, 0, DateTimeKind.Utc),
    };

    internal static readonly object[] Sections =
    [
${sections.join('\n')}
    ];

    internal static readonly object[] Fields =
    [
${fields.join('\n')}
    ];

    internal static readonly object[] Attachments =
    [
${attachments.join('\n')}
    ];
}
`;
}

const schema = await loadSchema();
const target = path.join(
  OUT_DIR,
  `ApplicationSchemaSeed.${schema.version.replace(/[^a-zA-Z0-9]/g, '')}.cs`
);
const next = emit(schema);

if (existsSync(target)) {
  const current = await readFile(target, 'utf8');
  if (current === next) {
    console.log(`unchanged  ${path.relative(REPO, target)}`);
    process.exit(0);
  }
  console.error(
    `REFUSED: ${path.relative(REPO, target)} already exists and would change.\n` +
      `A published schema version is history — bump the version in ` +
      `applicationSchema.ts instead of editing ${schema.version}.`
  );
  process.exit(1);
}

await writeFile(target, next, 'utf8');
console.log(
  `wrote      ${path.relative(REPO, target)}  ` +
    `(${schema.sections.length} sections, ${schema.fields.length} fields, ` +
    `${schema.attachments.length} attachment rules)`
);
